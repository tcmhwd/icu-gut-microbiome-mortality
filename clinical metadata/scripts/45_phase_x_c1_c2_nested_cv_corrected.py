# 2b. single-split OOF microbiome_prob -- kept EXACTLY as in 18, for the
#     full-data adjusted-OR/CI/p logistic regression only (task item 5: that
#     step is a full-data fit, not claiming to be out-of-fold, so it is not
#     affected by the CV-nesting bug and is left unchanged). NOT used for
#     any CV_AUROC number in this script.
