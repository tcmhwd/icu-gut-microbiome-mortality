single_split_skf = StratifiedKFold(n_splits=N_FOLDS, shuffle=True, random_state=SEED)


def single_split_oof(X, fit_predict_fn):
    p = np.full(len(y), np.nan)
    for tr, te in single_split_skf.split(X, y):
        p[te] = fit_predict_fn(X.iloc[tr], y[tr], X.iloc[te])
    return p


